def test_golden_vertex_and_edge_id_snapshot() -> None:
    vertex_keys = [_canon(vk) for vk in GEOMETRY.vertex_hexes]
    assert vertex_keys == GOLDEN_VERTEX_KEYS

    edge_keys = []
    for v1, v2 in GEOMETRY.edge_vertices:
        pair = tuple(sorted((vertex_keys[v1], vertex_keys[v2])))
        edge_keys.append(pair)
    assert edge_keys == GOLDEN_EDGE_KEYS
