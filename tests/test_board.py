"""Board geometry invariants and a golden id-snapshot regression guard.

Rule under test: the board must have exactly 19 land hexes, 54 vertices, and
72 edges (Almanac p. 2 component counts); every vertex has 2 or 3 neighbors
(perimeter vs. interior intersections); every edge has exactly 2 distinct
vertex endpoints; there are exactly 9 ports, each on a coastal edge with 2
distinct vertices; the desert hex gets no number token and starts holding the
robber; terrain and number-token multisets match the fixed distributions; and
no two 6/8 hexes are edge-adjacent (Almanac p. 13, fully-random set-up rule).
"""

import random
from collections import Counter

from engine.board import (
    GEOMETRY,
    NUM_EDGES,
    NUM_LAND_HEXES,
    NUM_PORTS,
    NUM_VERTICES,
    TERRAIN_COUNTS,
    TOKEN_MULTISET,
    Terrain,
    generate_board,
)


def _canon(
    vertex_key: frozenset[tuple[int, int, int]],
) -> tuple[tuple[int, int, int], ...]:
    return tuple(sorted(vertex_key))


def test_hex_and_vertex_and_edge_counts() -> None:
    assert len(GEOMETRY.land_hexes) == NUM_LAND_HEXES
    assert len(GEOMETRY.vertex_hexes) == NUM_VERTICES
    assert len(GEOMETRY.edge_vertices) == NUM_EDGES


def test_every_vertex_has_two_or_three_neighbors() -> None:
    for neighbors in GEOMETRY.vertex_neighbors:
        assert len(neighbors) in (2, 3)


def test_every_edge_has_two_distinct_endpoints() -> None:
    for v1, v2 in GEOMETRY.edge_vertices:
        assert v1 != v2


def test_exactly_nine_ports_on_coastal_edges_with_distinct_vertices() -> None:
    assert len(GEOMETRY.port_locations) == NUM_PORTS
    assert len(set(GEOMETRY.port_locations)) == NUM_PORTS
    for edge_id in GEOMETRY.port_locations:
        assert GEOMETRY.is_coastal_edge(edge_id)
        v1, v2 = GEOMETRY.edge_vertices[edge_id]
        assert v1 != v2


def test_desert_has_no_token_and_starts_with_robber() -> None:
    board = generate_board(random.Random(1))
    desert_hexes = [h for h, t in board.terrain.items() if t is Terrain.DESERT]
    assert len(desert_hexes) == 1
    desert = desert_hexes[0]
    assert desert not in board.tokens
    assert board.robber_hex == desert


def test_terrain_multiset_matches_fixed_counts() -> None:
    board = generate_board(random.Random(2))
    counts = Counter(board.terrain.values())
    for terrain, expected in TERRAIN_COUNTS.items():
        assert counts[terrain] == expected


def test_token_multiset_matches_fixed_counts() -> None:
    board = generate_board(random.Random(3))
    assert sorted(board.tokens.values()) == sorted(TOKEN_MULTISET)


def test_no_two_red_numbers_edge_adjacent() -> None:
    for seed in range(25):
        board = generate_board(random.Random(seed))
        red_hexes = [h for h, n in board.tokens.items() if n in (6, 8)]
        for i, a in enumerate(red_hexes):
            for b in red_hexes[i + 1 :]:
                assert not GEOMETRY.is_land(a) or b not in GEOMETRY.hex_neighbors(a)


